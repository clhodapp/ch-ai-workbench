"""The HM-emitted registry: the base part and the sandbox module parts.

The registry is generated by the home-manager module into
``$XDG_CONFIG_HOME/claude-code-sandbox/registry.json``; this tool only
reads it. Shape::

    {
      "base": "~/.config/claude-code-sandbox/parts/base.json",
      "modules": {"git": "~/.config/claude-code-sandbox/parts/module-git.json", ...},
      "baseModules": ["git"],
      "credentials": {"ssh-config": {"source": "...", "target": "ssh_config"}}
    }

``base`` and the ``modules`` values are absolute paths (the home-manager
symlinks into /nix/store, spelled with ``~`` above) to part JSON files,
which ``compose`` combines into one settings fragment.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from .files import ToolError, read_json


def config_dir() -> Path:
    override = os.environ.get("CLAUDE_CODE_SANDBOX_CONFIG")
    if override:
        return Path(override)
    xdg = os.environ.get("XDG_CONFIG_HOME")
    base = Path(xdg) if xdg else Path.home() / ".config"
    return base / "claude-code-sandbox"


class MaskedStore(ToolError):
    """A registry/fragment path is a symlink whose target is unreadable
    from here: the home-manager symlink points into /nix/store, and this
    process runs inside a masked-store sandbox whose allowRead closure
    does not include it. Callers that can degrade (status) should."""


def _masked_here(path: Path) -> bool:
    return path.is_symlink() and not path.exists()


def load_registry() -> dict[str, Any]:
    path = config_dir() / "registry.json"
    if _masked_here(path):
        raise MaskedStore(f"registry {path} is not readable from inside a masked-store sandbox")
    if not path.exists():
        raise ToolError(
            f"no registry at {path} — is the claude-code-sandbox home-manager "
            "module enabled and switched?"
        )
    return read_json(path)


def load_part(path_str: str | None, what: str) -> dict[str, Any]:
    if not path_str:
        raise ToolError(
            f"the registry names no file for {what}: re-run home-manager switch"
        )
    path = Path(path_str)
    if _masked_here(path):
        raise MaskedStore(f"{what} {path} is not readable from inside a masked-store sandbox")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as e:
        raise ToolError(
            f"{what} points at {path}, which does not exist: "
            "stale registry? re-run home-manager switch"
        ) from e
    if not isinstance(value, dict):
        raise ToolError(f"{what} {path} does not contain a JSON object")
    return value
