"""The HM-emitted registry: profile fragments.

The registry is generated by the home-manager module into
``$XDG_CONFIG_HOME/claude-code-sandbox/registry.json``; this tool only
reads it. Shape::

    {
      "profiles": {"default": "/nix/store/...-fragment.json", ...}
    }

``profiles`` values are paths to self-contained fragment JSON files.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from .files import ToolError, read_json


def config_dir() -> Path:
    override = os.environ.get("CLAUDE_CODE_SANDBOX_CONFIG")
    if override:
        return Path(override)
    xdg = os.environ.get("XDG_CONFIG_HOME")
    base = Path(xdg) if xdg else Path.home() / ".config"
    return base / "claude-code-sandbox"


class MaskedStore(ToolError):
    """A registry/fragment path is a symlink whose target is unreadable
    from here: the home-manager symlink points into /nix/store, and this
    process runs inside a masked-store sandbox whose allowRead closure
    does not include it. Callers that can degrade (status) should."""


def _masked_here(path: Path) -> bool:
    return path.is_symlink() and not path.exists()


def load_registry() -> dict[str, Any]:
    path = config_dir() / "registry.json"
    if _masked_here(path):
        raise MaskedStore(f"registry {path} is not readable from inside a masked-store sandbox")
    if not path.exists():
        raise ToolError(
            f"no registry at {path} — is the claude-code-sandbox home-manager "
            "module enabled and switched?"
        )
    return read_json(path)


def profile_names(registry: dict[str, Any]) -> list[str]:
    return sorted((registry.get("profiles") or {}).keys())


def load_fragment(registry: dict[str, Any], name: str) -> dict[str, Any]:
    profiles = registry.get("profiles") or {}
    if name not in profiles:
        raise ToolError(
            f"profile '{name}' is not in the registry "
            f"(known: {', '.join(sorted(profiles)) or 'none at all'})"
        )
    path = Path(profiles[name])
    if _masked_here(path):
        raise MaskedStore(
            f"profile '{name}' fragment {path} is not readable from inside a "
            "masked-store sandbox"
        )
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as e:
        raise ToolError(
            f"profile '{name}' points at {path}, which does not exist — "
            "stale registry? re-run home-manager switch"
        ) from e
    if not isinstance(value, dict):
        raise ToolError(f"fragment {path} does not contain a JSON object")
    return value


